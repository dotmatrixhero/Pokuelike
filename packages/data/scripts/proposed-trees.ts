/**
 * PROPOSED move trees — drafts for review in the Move Tree Atlas's
 * "proposed" mode. Nothing in this file is wired into `MOVES`; the game
 * does not read it. It exists so a tree can be browsed as a real node
 * graph before anyone commits to building it.
 *
 * Direct ask: "Add a proposed mode. I just want to see your trees before
 * you build em all."
 *
 * Deliberately NOT typed against `MoveTree`: several nodes here depend on
 * engine primitives that don't exist yet (see MOVES_DESIGN.md's round-six
 * primitives table). Those nodes carry `needsPrimitive` naming exactly
 * what would have to be built, and the atlas badges them — so a reviewer
 * can see at a glance which half of a tree is free and which half costs
 * engine work. Once a tree is approved, its nodes move into moves.ts and
 * get the real type; this file is the drafting surface, not a parallel
 * data source.
 */

export interface ProposedNode {
  id: string;
  name: string;
  cost: number;
  prerequisites?: string[];
  prerequisitesAnyOf?: string[][];
  excludes?: string[];
  leaning?: "aggression" | "boldness" | "sociability";
  grantsPassive?: { kind: string; value: number };
  grantsPassives?: Array<{ kind: string; value: number }>;
  delta: Record<string, unknown>;
  /** Names the engine primitive this node would need. Absent = buildable today. */
  needsPrimitive?: string;
  /** One line of design intent, shown in the atlas detail pane. */
  note?: string;
}

